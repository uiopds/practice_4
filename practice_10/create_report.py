def add_step(p_num, title_text, description_text, screenshot_label):
    h = doc.add_heading(f'{p_num}. {title_text}', level=2)
    h.paragraph_format.space_before = Pt(12)
    h.paragraph_format.space_after = Pt(4)
    p = doc.add_paragraph(description_text)
    p.paragraph_format.line_spacing = 1.15
    p.paragraph_format.space_after = Pt(6)
    p_box = doc.add_paragraph()
    p_box.paragraph_format.space_before = Pt(4)
    p_box.paragraph_format.space_after = Pt(10)
    r = p_box.add_run(f'[{screenshot_label}]')
    r.bold = True
    r.font.color.rgb = RGBColor(0x8B, 0x00, 0x00)

